#include <iostream>

int main(){
    int inteiro = 10; // tipo inteiro
    char caractere = 'A'; // tipo char
    double valorFlutuante = 0.5; // tipo decimal
    bool booleano = true; // tipo bolleano
    float _float = 0.1; // tipo float
    std::cout << "Inteiro: " << inteiro << "\n";
    std::cout << "Caractere: " << caractere << "\n";
    std::cout << "Double: " << valorFlutuante << "\n";
    std::cout << "Boolean: " << booleano << "\n";
    std::cout << "Float: " << _float << std::endl;
    return 0;
}